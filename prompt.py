def _group_beat_directive(group_key):
    """Unit 그룹(01-02 등)의 비트 지시. (v3.11)"""
    try:
        first = int(str(group_key).split("-")[0])
        second = int(str(group_key).split("-")[1])
    except (ValueError, IndexError):
        return ""
    d1 = build_beat_directive(first)
    d2 = build_beat_directive(second)
    if d1 and d2 and d1 != d2:
        return d1 + "\n\n" + d2
    return d1 or d2


def build_genre_mix_directive(genre, unit_no):
    """해당 Unit의 장르 배합 지시를 생성한다. (v3.10)

    복합 장르에서 Unit 위치에 따라 주/보조 장르 비중을 구체적으로 지시한다.
    원리만 주면 판단이 흐려지므로 Unit별 지시로 확정한다.
    """
    keys = detect_genre_keys(genre)
    if len(keys) < 2:
        return ""
    main, sub = keys[0], keys[1]

    if unit_no in (1, 2):
        phase = "미끼 구간"
        ratio = f"{main} 60% / {sub} 40%"
        note = (f"보조 장르({sub})를 적극 활용해 독자를 끌어들인다. "
                f"단 ★사건과 위협은 {main}가 담당★한다. "
                f"{sub}는 그 위협으로 진입하는 통로여야 한다.")
    elif unit_no in (3, 4, 5, 6):
        phase = "주 장르 확립 구간"
        ratio = f"{main} 85% / {sub} 15%"
        note = (f"{main}가 지배한다. {sub}는 장면 한둘로 최소화하고, "
                f"그마저도 {main}의 압박을 강화하는 방향으로 쓴다.")
    elif unit_no in (7, 8):
        phase = "완충 구간"
        ratio = f"{main} 70% / {sub} 30%"
        note = (f"미드포인트 전후다. {sub}를 한 번 더 배치해 호흡을 준다. "
                f"단 이 완충이 이후 {main} 최고조의 낙차를 키우는 장치여야 한다.")
    elif unit_no in (9, 10, 11):
        phase = "클라이맥스 진입 — 보조 장르 차단"
        ratio = f"{main} 100% / {sub} 0%"
        note = (f"★이 구간에 {sub} 장면을 넣지 마라.★ 긴장이 붕괴한다. "
                f"작가 완성 원고 실측: 클라이맥스 직전 챕터의 보조 장르 밀도 0. "
                f"{main}만 남긴다.")
    else:  # 12 이상
        phase = "회수 구간"
        ratio = f"{main} 60% / {sub} 40%"
        note = (f"{main}의 사건을 종결한 뒤 {sub} 라인을 정산한다. "
                f"깔아둔 관계·정서의 결말을 반드시 보여준다.")

    return f"""
[★ Unit {unit_no} 장르 배합 지시 (v3.10) ★]
현재 구간: {phase}
권장 비중: {ratio}
{note}
""".strip()


def _genre_block(genre):
    """장르 규칙 블록. 복합 장르면 주 장르 + 보조 장르 + 운용 원리를 제공한다. (v3.10)"""
    keys = detect_genre_keys(genre)
    tropes = detect_tropes(genre)
    main = keys[0]
    out = [get_genre_rules_block(main)]

    if len(keys) > 1:
        subs = keys[1:3]
        out.append(f"""
[복합 장르 — 주 장르 {main} / 보조 {' / '.join(subs)}]
★ 오프닝 DNA와 사건의 성격은 주 장르({main})가 결정한다. ★
독자를 붙잡는 것은 안온함이 아니라 불안이다.
""".strip())
        for sk in subs:
            r = GENRE_RULES.get(sk, GENRE_RULES["미지정"])
            out.append(
                f"[보조 장르: {sk}]\n"
                f"  핵심: {r['core']}\n"
                f"  재미의 본질: {r['genre_fun']}\n"
                f"  필수 요소: {' / '.join(r['must_have'][:2])}\n"
                f"  실패 패턴: {' / '.join(r['fails'][:2])}"
            )
        out.append(COMPOSITE_GENRE_PRINCIPLE)

    if tropes:
        out.append(
            f"[소재/설정: {', '.join(tropes)}]\n"
            f"  이것은 장르가 아니라 소재다. 장르 규칙({main})을 우선하되,\n"
            f"  이 소재가 주는 고유한 기대치를 충족시켜라."
        )

    return "\n\n".join(out)


