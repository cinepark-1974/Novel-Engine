_ROMCOM_PAT = ("로맨틱 코미디", "로맨틱코미디", "로코", "rom-com", "romcom")


def detect_genre_keys(genre_str):
    """장르 문자열에서 해당하는 모든 장르 키를 우선순위 순으로 반환. (v3.9)

    복합 장르를 하나로 뭉개지 않는다.
    예) "로맨틱 스릴러" → ["범죄/스릴러", "로맨스"]
        "판타지 로맨스" → ["판타지", "로맨스"]
        "무협 학원물"   → ["무협"]
    첫 번째가 주 장르(오프닝 DNA·사건 성격 결정), 나머지는 보조 장르.
    """
    if not genre_str:
        return ["미지정"]
    gl = str(genre_str).lower()
    found = []
    for kws, gk in GENRE_KEYWORD_MAP:
        if gk in found:
            continue
        if any(k in gl for k in kws):
            found.append(gk)
    if not found:
        return ["미지정"]
    found.sort(key=lambda g: GENRE_PRIORITY.get(g, 50))
    # 로맨틱 코미디는 코미디가 주도한다 (예외 처리)
    if any(p in gl for p in _ROMCOM_PAT) and "코미디" in found:
        found.remove("코미디")
        found.insert(0, "코미디")
    return found


def detect_genre_key(genre_str):
    """주 장르 하나를 반환. (하위 호환 유지)"""
    return detect_genre_keys(genre_str)[0]


